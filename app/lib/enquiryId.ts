// =============================================================================
// app/lib/enquiryId.ts   —  ENTRY ID, READ FROM THE SHEET'S Entry_ID COLUMN
// =============================================================================
// One job only: read the row's Entry_ID cell and return that text.
//
//     ENQU-00048      ENQ-00001      ENQP-00003      ENQPP-00008
//
// Nothing else is ever looked at. No other column is searched, no value is
// guessed, nothing is prefixed, padded or generated. If the Entry_ID cell is
// empty the result is '' and the UI says so — it never falls back to Serial_No,
// a PO number, a gate pass or any other cell.
// =============================================================================

/** 'Entry_ID' / 'entry id' / 'EntryId' / 'Entry ID '  ->  'entryid' */
export function entryIdKey(key: string): string {
  return String(key || "")
    .replace(/\(.*?\)/g, " ")
    .replace(/\b(auto|autogenerated|generated|system)\b/gi, " ")
    .replace(/[^a-z0-9]/gi, "")
    .toLowerCase();
}

/**
 * Reads one sheet cell as clean text.
 *
 * Cells pasted from Excel often carry zero-width spaces, non-breaking spaces or
 * soft hyphens. Those are invisible, so such a cell looks empty and the stored
 * id would be lost.
 */
export function readEntryIdCell(raw: unknown): string {
  if (raw === null || raw === undefined) return "";
  if (typeof raw === "number" || typeof raw === "boolean") return String(raw);
  if (typeof raw === "object") return "";
  return String(raw)
    .replace(/[\u200B-\u200D\uFEFF\u00AD]/g, "")
    .replace(/\u00A0/g, " ")
    .trim();
}

/**
 * True when the text is a real enquiry id (ENQ… or LETTERS-DIGITS) and not a
 * bill number, party code or document number.
 *
 *   ENQ-00001  ENQP-00003  ENQU-00048  ABC-123   -> true
 *   B-523/26-27   P0000133   2026-0187           -> false
 */
export function isEntryIdShape(value: unknown): boolean {
  const text = readEntryIdCell(value);
  if (!text || /\s/.test(text)) return false;
  return /^ENQ[\s/_-]?[A-Z0-9/-]*$/i.test(text) || /^[A-Z]{2,6}\s?-\s?\d{1,10}$/i.test(text);
}

/** The row's Entry_ID exactly as the sheet holds it. '' when that cell is empty. */
export function getEnquiryId(entry: Record<string, unknown>): string {
  if (!entry) return "";

  const direct = readEntryIdCell(entry.Entry_ID);
  if (direct) return direct;

  // Tolerate a header or alias that differs only by spacing/case, including the
  // "Enquiry_ID" wording and the camelCase alias the backend also sends.
  for (const key of Object.keys(entry)) {
    const normalized = entryIdKey(key);
    if (normalized !== "entryid" && normalized !== "enquiryid") continue;
    const value = readEntryIdCell(entry[key]);
    if (value) return value;
  }

  return "";
}

/** True when the sheet itself holds an Entry_ID for this row. */
export function hasEnquiryId(entry: Record<string, unknown>): boolean {
  return getEnquiryId(entry) !== "";
}

/**
 * Returns the row with `Entry_ID` set to the value the shared reader resolved.
 *
 * The user page, the admin table, the search box and the detail modal all read
 * `entry.Entry_ID` directly, so the value has to be present under that exact key
 * or a card renders without an ID even though the sheet has one. Applying this
 * once, where the data arrives, keeps every consumer consistent.
 */
export function withCanonicalEntryId(
  entry: Record<string, unknown>
): Record<string, unknown> {
  if (!entry) return entry;
  const id = getEnquiryId(entry);
  if (id === readEntryIdCell(entry.Entry_ID)) return entry;
  return { ...entry, Entry_ID: id };
}

/** Applies `withCanonicalEntryId` to a list, preserving order. */
export function canonicalizeEntryIds(
  entries: Record<string, unknown>[]
): Record<string, unknown>[] {
  return (entries || []).map(withCanonicalEntryId);
}

/**
 * INTERNAL navigation key only — never rendered.
 *
 * The task detail view is handed the row object directly, so this exists only to
 * give React list keys a stable unique value for rows without an Entry_ID.
 */
export function getEntryRef(entry: Record<string, unknown>, rowIndex = 0): string {
  const id = getEnquiryId(entry);
  if (id) return id;

  const serial = readEntryIdCell(entry?.Serial_No);
  if (serial && serial !== "0") return `SERIAL:${serial}`;

  return `ROW:${rowIndex}`;
}
